/**
 * Generates components/europe-map.ts: pre-projected SVG paths for the hero map.
 * Data: Natural Earth 1:50m (public domain) via the world-atlas package.
 *
 * Regenerate (the packages are only needed for this script):
 *   npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3
 *   node scripts/generate-europe-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature, mesh, merge } from "topojson-client";
import { geoPath, geoProjection } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
const out = process.argv[2] ?? new URL("../components/europe-map.ts", import.meta.url).pathname;

// Equirectangular, with longitudes compressed by cos(46°) so shapes look right at this latitude.
const LON_MIN = -10;
const LAT_MAX = 56.5;
const SCALE = 25.5; // px per degree of latitude
const COS = Math.cos((46 * Math.PI) / 180);
const W = 480;
const H = 530;

const projection = geoProjection((l, p) => [l * COS, p])
  .scale((SCALE * 180) / Math.PI)
  .translate([-LON_MIN * SCALE * COS, LAT_MAX * SCALE])
  .clipExtent([[-2, -2], [W + 2, H + 2]])
  .precision(0.2);
const path = geoPath(projection).digits(1);

const countries = topo.objects.countries;
const highlight = { france: "250", spain: "724", italy: "380", germany: "276", uk: "826" };

const land = path(merge(topo, countries.geometries));
const borders = path(mesh(topo, countries, (a, b) => a !== b));
const campuses = Object.fromEntries(
  Object.entries(highlight).map(([k, id]) => [k, path(feature(topo, countries.geometries.find((g) => g.id === id)))]),
);

writeFileSync(
  out,
  `// Generated by scripts/generate-europe-map.mjs from Natural Earth 1:50m (public domain). Do not edit by hand.
export const MAP = { LON_MIN: ${LON_MIN}, LAT_MAX: ${LAT_MAX}, SCALE: ${SCALE}, LON_SCALE: ${SCALE * COS}, W: ${W}, H: ${H} } as const;
export const LAND = ${JSON.stringify(land)};
export const BORDERS = ${JSON.stringify(borders)};
export const CAMPUS_COUNTRIES = ${JSON.stringify(campuses, null, 2)} as const;
`,
);
console.log("land", land.length, "borders", borders.length, Object.values(campuses).map((c) => c.length));
